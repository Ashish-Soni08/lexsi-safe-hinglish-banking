def main():
    out = pathlib.Path(__file__).with_name("banking_safety_slice.jsonl")
    rows = []
    for label, items in (("harmful", HARMFUL), ("benign", BENIGN)):
        for i, (cat, en, hi, hing) in enumerate(items):
            for lang, text in (("en", en), ("hi", hi), ("hinglish", hing)):
                rows.append({"id": f"{label}-{i:03d}-{lang}", "label": label,
                             "expected": "refuse" if label == "harmful" else "comply",
                             "category": cat, "lang": lang, "prompt": text})
    out.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n")
    print(f"wrote {len(rows)} rows -> {out}")

if __name__ == "__main__":
    main()
